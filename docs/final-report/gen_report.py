def figure(path, caption, width=16.5):
    full = os.path.join(IMG, path)
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.keep_with_next = True
    p.add_run().add_picture(full, width=Cm(width))
    fig_no[0] += 1
    c = para(f'[그림 {fig_no[0]}] {caption}', size=9, color=GREY, align=WD_ALIGN_PARAGRAPH.CENTER, after=8)
    return fig_no[0]


def table(head, rows, widths=None, caption=None, size=9, first_bold=False):
    if caption:
        tab_no[0] += 1
        cp = para(f'[표 {tab_no[0]}] {caption}', size=9.5, bold=True, after=2)
        cp.paragraph_format.keep_with_next = True
    t = doc.add_table(rows=1 + len(rows), cols=len(head))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for j, h in enumerate(head):
        c = t.rows[0].cells[j]; shade(c, HEAD_FILL); cell_text(c, h, bold=True, size=size, align=WD_ALIGN_PARAGRAPH.CENTER)
    for i, row in enumerate(rows, 1):
        for j, v in enumerate(row):
            cell_text(t.rows[i].cells[j], str(v), size=size, bold=(first_bold and j == 0))
    if widths:
        fix_widths(t, widths)
    para('', after=4)
    return t


