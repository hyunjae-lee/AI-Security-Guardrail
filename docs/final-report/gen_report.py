def bottom_border(cell):
    tcpr = cell._element.get_or_add_tcPr()
    b = OxmlElement('w:tcBorders')
    el = OxmlElement('w:bottom'); el.set(qn('w:val'), 'single'); el.set(qn('w:sz'), '12'); el.set(qn('w:color'), '1F3A5F')
    b.append(el); tcpr.append(b)


