const GLUE_PATTERNS = [
  [/([가-힣]+) (수) (있|없)/g, `$1${NB}$2${NB}$3`],
  [/([가-힣]+) (것)(입니다|이다|이|은|을|과|처럼|에|도|만|보다)/g, `$1${NB}$2$3`],
  [/([가-힣]+) (때)(문|까지|마다|는|에|도|와|를|가|만|부터|\s|,|\.|$)/g, `$1${NB}$2$3`],
  [/([가-힣]+) (뿐)(입니다|이다|만)/g, `$1${NB}$2$3`],
  [/([가-힣]+) (채|만큼|대로|줄|리|데)(\s|,|\.|은|는|를|가|에|로|$)/g, `$1${NB}$2$3`],
]

/** 화면에 나가는 한국어 문자열에 붙임을 적용한다. */
export function glue(text) {
  if (typeof text !== 'string') return text
  let out = text
  for (const term of GLUE_TERMS) {
    out = out.split(term).join(term.replace(/ /g, NB))
  }
  for (const [re, rep] of GLUE_PATTERNS) out = out.replace(re, rep)
  return out
}

